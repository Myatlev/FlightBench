#!/bin/bash
# Apply the FlightBench QEMU machine sources to a QEMU source tree.
# Usage: core/qemu/apply.sh <qemu-src-dir>   (idempotent)
#
# Applies core/qemu/patches/*.diff (git apply, skipped when already applied), copies
# hw/arm/nexus_xr.c and the emulator-independent device library
# (devices/src/*.c and its private *.h, devices/include/fb/*.h) and the flight dynamics models
# (fdm/src/*.c, fdm/include/fb/*.h) into <qemu>/hw/arm/fb-devices/ (public headers in fb/), and
# makes meson compile them all into the machine with fb-devices/ on the include path.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
DEV=$(cd "$HERE/../../devices" && pwd)
FDM=$(cd "$HERE/../../fdm" && pwd)
Q=${1:?usage: apply.sh <qemu-src-dir>}

# QEMU patches (core/qemu/patches/README.md): applied once; already applied = skipped. A copy of
# what was applied stays in <qemu>/.flightbench-patches/, so a newer version of a patch replaces
# the older one (reverse the old, apply the new).
mkdir -p "$Q/.flightbench-patches"
trap 'rm -f "$Q"/.flightbench-patches/.new-*' EXIT   # the LF copies below, also when a patch fails
for src in "$HERE"/patches/*.diff; do
  # a checkout with autocrlf (Windows) gives the patch CRLF endings, which git apply rejects:
  # work from an LF copy, named as the original so the stored copy keeps its name
  name=$(basename "$src"); p="$Q/.flightbench-patches/.new-$name"
  sed 's/\r$//' "$src" > "$p"
  if git -C "$Q" apply --reverse --check "$p" 2>/dev/null; then
    mv "$p" "$Q/.flightbench-patches/$name"
    continue
  fi
  old="$Q/.flightbench-patches/$name"
  reverted=
  if [ -f "$old" ] && git -C "$Q" apply --reverse --check "$old" 2>/dev/null; then
    git -C "$Q" apply --reverse "$old"
    reverted=1
    echo "reverted the previous $name"
  fi
  git -C "$Q" apply --check "$p" || {
    # leave the tree as it was: put the previous version back
    [ -n "$reverted" ] && git -C "$Q" apply "$old" && echo "re-applied the previous $name" >&2
    echo "apply.sh: $name does not apply to $Q; an older version applied before" \
         "apply.sh kept copies? restore the files it touches (git -C $Q checkout -- <files>)" >&2
    exit 1
  }
  git -C "$Q" apply "$p"
  mv "$p" "$Q/.flightbench-patches/$name"
  echo "applied $name"
done

cp "$HERE/hw/arm/nexus_xr.c" "$HERE/hw/arm/nexus_xr_ctl.c.inc" "$HERE/hw/arm/stm32_i2c.c.inc" \
   "$HERE/hw/arm/stm32_i2c_v1.c.inc" \
   "$HERE/hw/arm/stm32_soc.c.inc" "$HERE/hw/arm/fb_prof.c.inc" "$HERE/hw/arm/fb_fdm.c.inc" \
   "$HERE/hw/arm/fb_msp_modes.c.inc" "$HERE/hw/arm/fb_bench_state.c.inc" \
   "$HERE/hw/arm/fb_outputs.c.inc" "$Q/hw/arm/"
# build identification for the prof message (host.build)
{
  echo "/* generated by core/qemu/apply.sh */"
  echo "#define FB_BUILD \"flightbench $(git -C "$HERE" rev-parse --short HEAD 2>/dev/null || echo unknown)$(git -C "$HERE" diff --quiet HEAD -- "$HERE/.." "$HERE/../../devices" "$HERE/../../fdm" 2>/dev/null || echo +dirty)\""
} > "$Q/hw/arm/fb_build.h.tmp"
cmp -s "$Q/hw/arm/fb_build.h.tmp" "$Q/hw/arm/fb_build.h" 2>/dev/null && rm "$Q/hw/arm/fb_build.h.tmp" ||
  mv "$Q/hw/arm/fb_build.h.tmp" "$Q/hw/arm/fb_build.h"
rm -rf "$Q/hw/arm/fb-devices"
mkdir -p "$Q/hw/arm/fb-devices/fb"
cp "$DEV"/src/*.c "$DEV"/src/*.h "$Q/hw/arm/fb-devices/"
cp "$DEV"/include/fb/*.h "$Q/hw/arm/fb-devices/fb/"
cp "$FDM"/src/*.c "$FDM"/src/*.h "$Q/hw/arm/fb-devices/"
cp "$FDM"/include/fb/*.h "$Q/hw/arm/fb-devices/fb/"

grep -q "config NEXUS_XR" "$Q/hw/arm/Kconfig" || cat >> "$Q/hw/arm/Kconfig" <<'K'

config NEXUS_XR
    bool
    default y
    depends on TCG && ARM
    select ARM_V7M
    select STM32L4X5_USART
K
# the F4 USART model (stm32f2xx_usart) came with the speedybee-f405-wing machine
grep -A6 "config NEXUS_XR" "$Q/hw/arm/Kconfig" | grep -q "STM32F2XX_USART" ||
  sed -i '/^config NEXUS_XR$/,/^$/s/^    select STM32L4X5_USART$/    select STM32L4X5_USART\n    select STM32F2XX_USART/' "$Q/hw/arm/Kconfig"

FILES="'nexus_xr.c'"
for f in "$DEV"/src/*.c "$FDM"/src/*.c; do FILES="$FILES, 'fb-devices/$(basename "$f")'"; done
# fb-devices/ on the include path: headers include each other as "fb/<name>.h", which does not
# resolve from fb-devices/fb/ itself (the .c files next to them find fb/ on their own)
LINE="arm_common_ss.add(when: 'CONFIG_NEXUS_XR', if_true: [files($FILES), declare_dependency(include_directories: include_directories('fb-devices'))])"
M="$Q/hw/arm/meson.build"
if grep -q "CONFIG_NEXUS_XR" "$M"; then
  grep -v "CONFIG_NEXUS_XR" "$M" > "$M.tmp"
else
  cp "$M" "$M.tmp"
fi
# insert before the netduinoplus2 line (first arm_common_ss.add of a board)
awk -v l="$LINE" '!done && /CONFIG_NETDUINOPLUS2/ { print l; done=1 } { print }' "$M.tmp" > "$M"
rm "$M.tmp"
grep -qF "$LINE" "$M"
echo "applied FlightBench machine sources to $Q ($FILES)"
